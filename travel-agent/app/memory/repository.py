from typing import Any, Protocol


class ConversationRepository(Protocol):
    def initialize(self, retention_days: int = 90) -> None: ...
    def close(self) -> None: ...
    def check_rate(self, owner: str, limit: int) -> None: ...
    def list_conversations(self, owner: str) -> list[dict]: ...
    def conversation(self, owner: str, conversation_id: str) -> dict: ...
    def begin(self, owner: str, conversation_id: str | None, prompt: str) -> tuple[str, str]: ...
    def finish(self, owner: str, conversation_id: str, lease: str, prompt: str, result: Any) -> None: ...
    def release(self, owner: str, conversation_id: str, lease: str) -> None: ...
    def history(self, owner: str, conversation_id: str) -> list[dict]: ...
    def recall(self, owner: str, prompt: str, conversation_id: str) -> list[dict]: ...
    def delete_conversation(self, owner: str, conversation_id: str) -> None: ...
    def forget(self, owner: str) -> None: ...
